"""Collect installed dependency license text; does not fetch or publish anything."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
entries = []
go_environment = subprocess.check_output(['go', 'env', 'GOROOT', 'GOVERSION'], cwd=root, text=True).splitlines()
entries.append(("Go standard library " + go_environment[1], (Path(go_environment[0]) / "LICENSE").read_text().strip()))

def license_text(folder, fallback=None):
    files = []
    for path in folder.iterdir():
        if path.is_file() and path.name.lower().startswith(("license", "licence", "copying", "notice")):
            files.append(path)
    if not files:
        if fallback is not None:
            return fallback.read_text().strip()
        raise RuntimeError(f"Missing dependency license: {folder.name}")
    return "\n\n".join(path.read_text(errors="replace").strip() for path in sorted(files))

lock = json.loads((root / "frontend/package-lock.json").read_text())
for name, package in lock["packages"].items():
    if not name or package.get("dev") or not name.startswith("node_modules/"):
        continue
    folder = root / "frontend" / name
    fallback = None
    if name == 'node_modules/@lobehub/icons-static-svg':
        fallback = root / 'build/licenses/LobeIcons.txt'
    elif name == 'node_modules/@wailsio/runtime':
        fallback = root / 'build/licenses/Wails.txt'
    entries.append((name.removeprefix("node_modules/") + " " + package["version"], license_text(folder, fallback)))

data = subprocess.check_output(['go', 'list', '-deps', '-json', '.'], cwd=root, text=True)
decoder = json.JSONDecoder()
position = 0
modules = set()
while position < len(data):
    if data[position].isspace():
        position += 1
        continue
    dependency, position = decoder.raw_decode(data, position)
    package = dependency.get('Module')
    if not package or package.get("Main") or package['Path'] in modules:
        continue
    modules.add(package['Path'])
    text = license_text(Path(package["Dir"]))
    if package["Path"] in {"github.com/hashicorp/go-retryablehttp", "github.com/hashicorp/go-cleanhttp"}:
        text = f"Unmodified source: https://{package['Path']}/tree/{package['Version']}\n\n" + text
    entries.append((package["Path"] + " " + package["Version"], text))

entries.append(("Vercel Skills Agent location registry", (root / "build/licenses/VercelSkills.txt").read_text().strip()))
entries.append(("Devicon v2.17.0 — Visual Studio Code icon", (root / "build/licenses/Devicon.txt").read_text().strip()))
entries.append(("Simple Icons — Zed icon", (root / "build/licenses/SimpleIcons.txt").read_text().strip()))
output = "# Third-party notices\n\nGenerated by `script/notices.py` from the pinned, installed dependencies. Icons and dependency names remain the property of their respective owners.\n"
for name, text in sorted(entries):
    output += f"\n## {name}\n\n{text}\n"
(root / "THIRD_PARTY_NOTICES.md").write_text(output)
print(f"Collected {len(entries)} dependency notices.")
